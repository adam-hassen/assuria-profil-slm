def construire(ident, premier, reponses, attendu, coupee):
    R = random.Random(ident)
    tours = [("Conseiller", agent.ACCUEIL), ("Client", premier)]
    apres_refus = False
    rep = {CLES[k]: v for k, v in reponses.items()}
    for champ in sorted(rep, key=ORDRE.index):
        texte = rep[champ]
        debut = "Pas de problème, nous continuons sans cette information. " if apres_refus else R.choice(["", "", "Merci. ", "D'accord. ", "Très bien. "])
        question = agent.QUESTION[champ] if champ != "type_vehicule" else "Souhaitez-vous assurer une voiture ou une moto ?"
        tours.append(("Conseiller", debut + question))
        apres_refus = texte.startswith("!")
        tours.append(("Client", texte.lstrip("!")))
    profil = {k: None for k in NOMS}
    inconnues = set(attendu) - set(NOMS)
    assert not inconnues, (ident, inconnues)
    profil.update(attendu)
    return tours, profil


def main() -> int:
    sortie = RACINE / "donnees"
    with open(sortie / "test_ecrit.jsonl", "w", encoding="utf-8") as f1, \
            open(sortie / "test_ecrit_conversations.jsonl", "w", encoding="utf-8") as f2:
        for ident, premier, reponses, attendu, coupee in CONVERSATIONS:
            tours, profil = construire(ident, premier, reponses, attendu, coupee)
            conv = "\n".join(f"{qui} : {t}" for qui, t in tours)
            f1.write(json.dumps({"messages": [{"role": "system", "content": CONSIGNE},
                                              {"role": "user", "content": message_utilisateur(conv)},
                                              {"role": "assistant", "content": json.dumps(profil, ensure_ascii=False)}]},
                                ensure_ascii=False) + "\n")
            f2.write(json.dumps({"id_profil": ident, "coupee": coupee, "tours": tours, "profil_attendu": profil},
                                ensure_ascii=False) + "\n")
    print(f"{len(CONVERSATIONS)} conversations écrites dans {sortie}")
    return 0


